export const PX_ROWS = 7;

export interface Pixel {
  x: number;
  y: number;
  accent: boolean;
  char: number;
}

export interface PixelLayout {
  width: number;
  height: number;
  pixels: Pixel[];
  chars: { x: number; w: number; ch: string; accent: boolean }[];
}

/**
 * Layout a single line. Wrap segments in {braces} to mark them as accent.
 * e.g. "{$}THREE" → "$" is accent.
 */
export function layoutPixelText(text: string, spacing = 1): PixelLayout {
  const pixels: Pixel[] = [];
  const chars: PixelLayout["chars"] = [];
  let x = 0;
  let accent = false;
  let ci = 0;
  for (const raw of text) {
    if (raw === "{") {
      accent = true;
      continue;
    }
    if (raw === "}") {
      accent = false;
      continue;
    }
    const ch = raw.toUpperCase();
    const glyph = G[ch] ?? G["?"];
    const w = glyph[0].length;
    glyph.forEach((row, y) => {
      for (let gx = 0; gx < w; gx++) {
        if (row[gx] === "#") pixels.push({ x: x + gx, y, accent, char: ci });
      }
    });
    chars.push({ x, w, ch, accent });
    x += w + spacing;
    ci++;
  }
  return { width: Math.max(1, x - spacing), height: PX_ROWS, pixels, chars };
}
